"""
\n -> New Line
\t -> Tab Space
\\ -> Backslash
\" -> Double Quotes
\' -> Single Quotes
"""

print("Hello\nworld")
print("Hello\tPriyanshu")

# home \ house
print("Home\\House")

print("My name is \"Priyanshu\" Gupta")

print('My name is "Priyanshu" Gupta')
print('My name is \'Priyanshu\' Gupta')