"""
Q5: Take a number as input. Print the result of that number raised to the
power of 3 using **. Also print what // 7 and % 7 give for the same number.
"""

num = int(input("Enter a number : "))

print(f"{num} raise to power 3 = {num ** 3}")
print(f"num // 7 : {num // 7} ")
print(f"num % 7 : {num % 7} ")